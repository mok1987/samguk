def _pair_quality(y):
    q = {0: 1.0, 1: 0, 2: -1.0}[P[y, 3]] + {0: -0.8, 1: 0, 2: 0.6}[P[y, 11]]
    q += {0: 0.6, 1: 0.2, 2: -0.6}[P[y, 13]]
    return q
def _pair_score(x, y):
    s = sum(1.0 for q in PAIR_COMP if P[x, q] != P[y, q]) + _pair_quality(y)
    if P[x, 3] == 0 and P[y, 3] == 0: s += 0.5
    if P[x, 0] == 0 and P[y, 0] == 0: s -= 1.0
    if P[x, 13] == 2 and P[y, 13] == 2: s -= 1.0
    return s
def partners(types, traits):
    use = np.zeros(30); out = {}
    for x in range(30):
        cand = sorted(((_pair_score(x, y) - 0.25 * use[y], y) for y in range(30) if y != x and NAMES[y] not in PAIR_EXCLUDE), reverse=True)
        pick, tset = [], set()
        for _, y in cand:
            if len(pick) == 4: break
            if types[NAMES[y]] in tset and len(tset) < 3: continue
            pick.append(y); tset.add(types[NAMES[y]])
        for y in pick: use[y] += 1
        res, used = [], set()
        for y in pick:  # 가장 크게 다른 문항으로 이유 한 줄 (같은 이유가 겹치지 않게)
            qs = sorted([q for q in PAIR_COMP if P[x, q] != P[y, q]], key=lambda q: (-abs(P[x, q] - P[y, q]), [4, 12, 2, 15].index(q)))
            why = next((WHY[q][P[y, q]] for q in qs if WHY[q][P[y, q]] not in used), None)
            if why is None: why = '강점: ' + ', '.join(traits[NAMES[y]][:2])
            used.add(why); res.append({'n': NAMES[y], 'why': why})
        out[NAMES[x]] = res
    return out

